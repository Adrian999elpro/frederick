-- Synthetic accounts and ballots only. No email is sent; every change rolls back.
begin;
do $test$
declare a uuid:=gen_random_uuid(); b uuid:=gen_random_uuid(); staff uuid:=gen_random_uuid();
 c uuid; poll uuid; named uuid; app uuid; opt uuid; token uuid; ticket uuid; result jsonb; blocked boolean;
 uid_a text:=upper(substr(replace(a::text,'-',''),1,14));
 uid_b text:=upper(substr(replace(b::text,'-',''),1,14));
 uid_staff text:=upper(substr(replace(staff::text,'-',''),1,14));
begin
 insert into auth.users(id,email,raw_app_meta_data,raw_user_meta_data,email_confirmed_at)
 values(a,'qa-'||a||'@example.invalid','{"provider":"email"}','{"full_name":"QA Voter A"}',now()),
 (b,'qa-'||b||'@example.invalid','{"provider":"email"}','{"full_name":"QA Voter B"}',now()),
 (staff,'qa-'||staff||'@example.invalid','{"provider":"email"}','{"full_name":"QA Council Staff"}',now());
 update public.profiles set role_id=(select id from public.roles where name='encargado_consejo') where id=staff;
 insert into public.nfc_cards(profile_id,card_uid,card_type,active) values(a,uid_a,'estudiante',true),(b,uid_b,'estudiante',true),(staff,uid_staff,'admin',true);
 perform set_config('request.jwt.claims',jsonb_build_object('sub',staff,'role','authenticated')::text,true);
 set local role authenticated;
 c:=public.create_school_poll('council','QA Council','Plan del consejo escolar',60,true);
 if exists(select 1 from public.school_polls where id=c and applications_open) then raise exception 'applications start open';end if;
 perform set_config('request.jwt.claims',jsonb_build_object('sub',a,'role','authenticated')::text,true);
 blocked:=false;
 begin perform public.set_council_applications_open(c,true);exception when insufficient_privilege then blocked:=true;end;
 if not blocked then raise exception 'student opened applications';end if;
 blocked:=false;
 begin perform public.submit_council_application(c,'QA List',repeat('Plan escolar. ',6));exception when raise_exception then if sqlerrm='applications_closed' then blocked:=true;else raise;end if;end;
 if not blocked then raise exception 'closed applications accepted';end if;
 perform set_config('request.jwt.claims',jsonb_build_object('sub',staff,'role','authenticated')::text,true);
 perform public.set_council_applications_open(c,true);
 perform set_config('request.jwt.claims',jsonb_build_object('sub',a,'role','authenticated')::text,true);
 perform public.submit_council_application(c,'QA List',repeat('Plan escolar. ',6));
 select id into app from public.council_applications where poll_id=c;
 blocked:=false;
 begin perform public.review_council_application(app,true,'');exception when insufficient_privilege then blocked:=true;end;
 if not blocked then raise exception 'student approved self';end if;
 perform set_config('request.jwt.claims',jsonb_build_object('sub',staff,'role','authenticated')::text,true);
 blocked:=false;
 begin perform public.review_council_application(app,false,'');exception when raise_exception then if sqlerrm='reason_required' then blocked:=true;else raise;end if;end;
 if not blocked then raise exception 'rejection without reason';end if;
 perform public.review_council_application(app,false,'Agrega fechas para las actividades.');
 perform set_config('request.jwt.claims',jsonb_build_object('sub',a,'role','authenticated')::text,true);
 if not exists(select 1 from public.council_applications where id=app and reason='Agrega fechas para las actividades.' and status='rejected') then raise exception 'rejection not visible';end if;
 perform public.submit_council_application(c,'QA List',repeat('Plan con fechas. ',6));
 perform set_config('request.jwt.claims',jsonb_build_object('sub',staff,'role','authenticated')::text,true);
 perform public.review_council_application(app,true,'Aprobada');
 if not exists(select 1 from public.school_poll_options where poll_id=c and application_id=app) then raise exception 'accepted list missing';end if;
 perform public.change_school_poll_status(c,'open');
 blocked:=false;
 begin perform public.set_council_applications_open(c,true);exception when raise_exception then if sqlerrm='applications_closed' then blocked:=true;else raise;end if;end;
 if not blocked then raise exception 'reopened applications after voting';end if;
 blocked:=false;
 begin perform public.create_school_poll('custom','Invalid duration','Motivo suficientemente largo',0,true,array['A','B']);exception when check_violation then blocked:=true;end;
 if not blocked then raise exception 'duration optional';end if;
 poll:=public.create_school_poll('custom','QA Secret','Elegir actividad escolar',60,true,array['A','B']);
 perform public.change_school_poll_status(poll,'open');
 select id into opt from public.school_poll_options where poll_id=poll and label='A';
 blocked:=false;
 begin perform public.cast_school_poll_vote(gen_random_uuid(),opt);exception when raise_exception then if sqlerrm='scan_required' then blocked:=true;else raise;end if;end;
 if not blocked then raise exception 'vote without scan';end if;
 ticket:=(public.scan_school_poll_card(poll,uid_a)->>'ticket')::uuid;
 perform set_config('request.jwt.claims',jsonb_build_object('sub',b,'role','authenticated')::text,true);
 blocked:=false;
 begin perform public.cast_school_poll_vote(ticket,opt);exception when raise_exception then if sqlerrm='scan_required' then blocked:=true;else raise;end if;end;
 if not blocked then raise exception 'stolen operator ticket';end if;
 blocked:=false;
 begin perform public.scan_school_poll_card(poll,uid_a);exception when insufficient_privilege then blocked:=true;end;
 if not blocked then raise exception 'student scanned someone else';end if;
 perform set_config('request.jwt.claims',jsonb_build_object('sub',staff,'role','authenticated')::text,true);
 perform public.cast_school_poll_vote(ticket,opt);
 blocked:=false;
 begin perform public.cast_school_poll_vote(ticket,opt);exception when raise_exception then if sqlerrm='scan_required' then blocked:=true;else raise;end if;end;
 if not blocked then raise exception 'reused vote ticket';end if;
 blocked:=false;
 begin perform public.scan_school_poll_card(poll,uid_a);exception when raise_exception then if sqlerrm='already_voted' then blocked:=true;else raise;end if;end;
 if not blocked then raise exception 'duplicate voter';end if;
 result:=public.school_poll_results(poll);
 if (result->>'total')::int<>1 or (result->>'no_vote')::int<>(result->>'eligible')::int-1 then raise exception 'participation counts wrong';end if;
 if exists(select 1 from jsonb_array_elements(result->'participants') p where p->>'choice' is not null) then raise exception 'secret vote choice linked';end if;
 reset role;
 if exists(select 1 from public.school_poll_votes where poll_id=poll and student_id is not null) then raise exception 'secret vote identity stored';end if;
 set local role authenticated;
 perform public.change_school_poll_status(poll,'close');
 named:=public.create_school_poll('custom','QA Named','Elegir actividad escolar',60,false,array['A','B']);
 perform public.change_school_poll_status(named,'open');
 select id into opt from public.school_poll_options where poll_id=named and label='B';
 ticket:=(public.scan_school_poll_card(named,uid_a)->>'ticket')::uuid;
 perform public.cast_school_poll_vote(ticket,opt);
 perform public.change_school_poll_status(named,'close');
 perform set_config('request.jwt.claims',jsonb_build_object('sub',b,'role','authenticated')::text,true);
 result:=public.school_poll_results(named);
 if not exists(select 1 from jsonb_array_elements(result->'participants') p where p->>'name'='QA Voter A' and p->>'choice'='B') then raise exception 'named result missing';end if;
 if jsonb_array_length(public.school_poll_results(poll)->'participants')<>0 then raise exception 'student sees secret participants';end if;
 blocked:=false;
 begin perform public.terminal_student_profile(uid_a);exception when insufficient_privilege then blocked:=true;end;
 if not blocked then raise exception 'student accessed terminal lookup';end if;
 perform set_config('request.jwt.claims',jsonb_build_object('sub',staff,'role','authenticated')::text,true);
 blocked:=false;
 begin perform public.authorize_terminal_card(uid_a);exception when insufficient_privilege then blocked:=true;end;
 if not blocked then raise exception 'student card unlocks';end if;
 result:=public.terminal_student_profile(uid_a);
 if result->>'id'<>a::text or result ? 'email' or result ? 'phone' then raise exception 'terminal profile unsafe';end if;
 token:=public.authorize_terminal_card(uid_staff);
 reset role;
 set local role anon;
 if not public.consume_terminal_unlock(token) then raise exception 'authorized card token failed';end if;
 if public.consume_terminal_unlock(token) or public.consume_terminal_unlock(gen_random_uuid()) then raise exception 'unlock token reusable';end if;
 reset role;
end $test$;
rollback;
select 'Passed council windows, review, NFC voting, one vote, secret/named results and terminal authorization. Rolled back all test data.' as result;

